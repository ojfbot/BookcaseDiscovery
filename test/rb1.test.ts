// RB-1: the re-baseline's box set (F-0i's partition less NB-3's shipped causes) and its loader. Synthetic data only.
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { NB3_SHIP } from "../src/eval/nb3.ts";
import { boxSetDrops, loadBoxSet, type Nb3Flag, type PartitionRow } from "../src/eval/rb1.ts";
import { at, placeSection, SECTION, show, withRebaseline } from "../src/eval/rb1-cli.ts";

const row = (id: string, state: PartitionRow["state"]): PartitionRow => ({ id, state, reason: state === "dropped" ? "piece-of" : null, changed: false, outline: [] });

describe("RB-1 box set", () => {
  const partition = [row("p:0", "kept"), row("p:1", "dropped"), row("p:2", "kept"), row("p:3", "kept")];
  const flags: Nb3Flag[] = [
    { id: "p:0", causes: ["on-lip"] },
    { id: "p:1", causes: ["on-lip"] }, // dropped by the partition first
    { id: "p:2", causes: ["depth", "on-lip"] }, // first cause is the one counted
    { id: "p:3", causes: ["pixel"] },
  ];

  it("drops the partition's dropped boxes and kept boxes whose first cause ships", () => {
    expect(NB3_SHIP).toEqual({ "on-lip": true, depth: false, pixel: false });
    const drops = boxSetDrops(partition, flags);
    expect([...drops].sort()).toEqual([
      ["p:0", "on-lip"],
      ["p:1", "f0i-dropped"],
    ]);
  });

  it("never lists a box the partition did not see", () => {
    expect(boxSetDrops(partition, [{ id: "q:9", causes: ["on-lip"] }]).has("q:9")).toBe(false);
  });

  it("loads both files from the data root and refuses a missing one", () => {
    const root = mkdtempSync(join(tmpdir(), "rb1-"));
    try {
      expect(() => loadBoxSet("pilot-000", root)).toThrow(/F-0i partition/);
      mkdirSync(join(root, "private", "f0i", "yardstick-library-b2"), { recursive: true });
      writeFileSync(join(root, "private", "f0i", "yardstick-library-b2", "partition.jsonl"), partition.map((r) => JSON.stringify(r)).join("\n") + "\n");
      expect(() => loadBoxSet("yardstick", root)).toThrow(/NB-3 flags/);
      mkdirSync(join(root, "private", "nb3", "yardstick"), { recursive: true });
      writeFileSync(join(root, "private", "nb3", "yardstick", "flags.jsonl"), flags.map((r) => JSON.stringify(r)).join("\n") + "\n");
      const box = loadBoxSet("yardstick", root);
      expect(["p:0", "p:1", "p:2", "p:3", "q:9"].map(box.keeps)).toEqual([false, false, true, true, true]);
      expect(box.rows.size).toBe(4);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});

describe("RB-1 summary", () => {
  it("reads paths and prints numbers, intervals, counts and verdicts", () => {
    const m = { a: { b: [0.5, 0.25, 0.75], c: { n: 12, lo: 9, hi: 15 }, d: { delta: -0.4, lo: -1.4, hi: 0.6 }, e: true } };
    expect(at(m, "a.b")).toEqual([0.5, 0.25, 0.75]);
    expect(at(m, "a.x.y")).toBeUndefined();
    expect(show(at(m, "a.b"), 100, 1)).toBe("50.0 (25.0 to 75.0)");
    expect(show(at(m, "a.c"), 1, 0)).toBe("12 (9 to 15)");
    expect(show(at(m, "a.d"), 1, 1)).toBe("-0.4 (-1.4 to 0.6)");
    expect(show(at(m, "a.e"))).toBe("yes");
    expect(show(undefined)).toBe("–");
  });

  it("places the section above the generated marker once, and replaces it on a re-run", () => {
    const report = "# X\n\nprose\n\n<!-- generated by x: edit above this line -->\n## table\n";
    const one = placeSection(report, `${SECTION}\n\nfirst\n`);
    expect(one.indexOf(SECTION)).toBeLessThan(one.indexOf("<!-- generated"));
    const two = placeSection(one, `${SECTION}\n\nsecond\n`);
    expect(two.split(SECTION).length).toBe(2);
    expect(two).toContain("second");
    expect(two).not.toContain("first");
    expect(two.endsWith("## table\n")).toBe(true);
  });

  it("appends the block as the last key without reformatting, and replaces it", () => {
    const text = '{"card": "X", "n": [1,2,3]}\n';
    const one = withRebaseline(text, { run: "RB1" });
    expect(JSON.parse(one)).toEqual({ card: "X", n: [1, 2, 3], rebaseline: { run: "RB1" } });
    expect(one.startsWith('{"card": "X", "n": [1,2,3]')).toBe(true);
    expect(JSON.parse(withRebaseline(one, { run: "RB1", v: 2 })).rebaseline).toEqual({ run: "RB1", v: 2 });
  });
});
