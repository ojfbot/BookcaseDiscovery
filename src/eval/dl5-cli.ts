// DL-5 runner: eval hygiene, counts only.
//
//   node src/eval/dl5-cli.ts analyse   # evals/DL5/metrics.json and the tables of evals/DL5/report.md
//
// Reads TS-0's latest label-ledger version and F-0g's copy groups (pilot-000), F-0's yardstick stage caches and the
// Library Dataset's annotation list under the data root, and every evals/<card>/{metrics.json,prereg.md,report.md}.
// Writes only counts: sets by role, works and copies on both sides of the frozen split, yardstick reuse by card and
// the size of each yardstick part. No ids, titles, paths or model output. Changes no split. CPU only.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { dataRoot } from "../ledger/images.ts";
import { GATED_BY_READING, leakage, ruleOfThree, yardstickParts, yardstickUse, type CardEval, type CopyMember, type LeakRow, type Use } from "./dl5.ts";
import { readJsonl } from "./f0.ts";
import { compactJson, parseCsv } from "./q1-cli.ts";
import { SET_REGISTRY, setsByRole, TRAINABLE_ROLES } from "./set-roles.ts";

const REPO = fileURLToPath(new URL("../../", import.meta.url));
const ROOT = dataRoot();
const OUT = join(REPO, "evals", "DL5");
const MARK = "<!-- generated by `node src/eval/dl5-cli.ts analyse`: edit above this line -->";
/** Slice sizes the quarantine options are costed at (images). */
const SLICES = [40, 100, 150] as const;

const log = (s: string) => console.error(`[dl5] ${s}`);
const imageOf = (boxId: string) => boxId.slice(0, boxId.lastIndexOf(":"));
const r4 = (x: number | null) => (x === null ? null : Math.round(x * 10000) / 10000);

function splitLeakage() {
  const dir = join(ROOT, "datasets", "label-ledger");
  const { version } = JSON.parse(readFileSync(join(dir, "latest.json"), "utf8")) as { version: string };
  const rows = readJsonl<LeakRow & { set: string }>(join(dir, version, "labels.jsonl"));
  const manifest = JSON.parse(readFileSync(join(dir, version, "manifest.json"), "utf8")) as { photos: { sha256: string; split: string; storeId: string | null; bookcaseId: string | null; captureGroup: string }[] };
  const split = new Map(manifest.photos.map((p) => [p.sha256, p.split]));
  const sets = [...new Set(rows.map((r) => r.set))].sort();
  const copies: CopyMember[] = sets.flatMap((set) => {
    const p = join(ROOT, "private", "f0g", set, "copies.jsonl");
    return existsSync(p) ? readJsonl<{ id: string; group: number | string }>(p).map((c) => ({ group: `${set}|${c.group}`, imageId: imageOf(c.id) })) : [];
  });
  return {
    version,
    sets,
    manifest: {
      photos: manifest.photos.length,
      bySplit: Object.fromEntries(["train", "val", "held-out"].map((s) => [s, manifest.photos.filter((p) => p.split === s).length])),
      captureGroups: new Set(manifest.photos.map((p) => p.captureGroup)).size,
      withStore: manifest.photos.filter((p) => p.storeId).length,
      withBookcase: manifest.photos.filter((p) => p.bookcaseId).length,
    },
    ...leakage(rows, copies, (id) => split.get(id)),
  };
}

function cardEvals(): CardEval[] {
  const dir = join(REPO, "evals");
  return readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && d.name !== "DL5" && existsSync(join(dir, d.name, "metrics.json")))
    .map((d) => d.name)
    .sort()
    .map((card) => {
      const read = (f: string) => (existsSync(join(dir, card, f)) ? readFileSync(join(dir, card, f), "utf8") : "");
      return { card, metrics: JSON.parse(read("metrics.json")), text: `${read("prereg.md")}\n${read("report.md")}` };
    });
}

function reuse() {
  const cards = cardEvals().map((e) => ({ card: e.card, prereg: existsSync(join(REPO, "evals", e.card, "prereg.md")), ...yardstickUse(e) }));
  const count = (u: Use) => cards.filter((c) => c.use === u).length;
  return {
    cards: cards.length,
    byUse: { gated: count("gated"), read: count("read"), "not read": count("not read") },
    gatedVia: Object.fromEntries(["boolean metric", "keep paragraph", "by reading"].map((v) => [v, cards.filter((c) => c.via === v).length])),
    byCard: Object.fromEntries(cards.map((c) => [c.card, c.via ? `${c.use} (${c.via})` : c.use])),
    byReading: GATED_BY_READING,
  };
}

/** The yardstick's parts: F-0's 40-image sample, the smoke-test stride, the rest of the annotated Library Dataset, the box set. */
function parts(readers: number) {
  const lib = join(ROOT, "proxy", "library-dataset");
  const ann = parseCsv(readFileSync(join(lib, "data", "annotations", "library_books_annotations.csv"), "utf8"));
  const withBooks = [...new Set(ann.filter((a) => a.not_book !== "True").map((a) => a.image_name!))].filter((n) => existsSync(join(lib, "images", n))).sort();
  const books = new Map<string, number>();
  /** A book's key across images: its ISBN, else its lower-cased title. */
  const keysOf = new Map<string, Set<string>>();
  for (const a of ann) {
    if (a.not_book === "True") continue;
    books.set(a.image_name!, (books.get(a.image_name!) ?? 0) + 1);
    const key = (a.isbn ?? "").replace(/\D/g, "") || (a.title ?? "").toLowerCase().replace(/\s+/g, " ").trim();
    if (key) keysOf.set(a.image_name!, (keysOf.get(a.image_name!) ?? new Set()).add(key));
  }
  const { step, sample, smoke } = yardstickParts(withBooks.length);
  const name = (i: number) => withBooks[i]!.replace(/\.jpg$/i, "");
  const sampleIds = new Set(sample.map(name)), smokeIds = new Set(smoke.map(name));
  const stages = readdirSync(join(ROOT, "f0")).filter((d) => d.startsWith("yardstick") && existsSync(join(ROOT, "f0", d, "detect.jsonl")));
  const cached = new Set<string>();
  const stageMatchesSample = stages.filter((d) => {
    const ids = new Set(readJsonl<{ id: string }>(join(ROOT, "f0", d, "detect.jsonl")).map((r) => r.id));
    for (const id of ids) cached.add(id);
    return ids.size === sampleIds.size && [...ids].every((id) => sampleIds.has(id));
  }).length;
  const extra = [...cached].filter((id) => !sampleIds.has(id));
  const touched = new Set([...sampleIds, ...smokeIds, ...extra]);
  const rest = withBooks.map((n) => n.replace(/\.jpg$/i, "")).filter((id) => !touched.has(id));
  const booksOf = (ids: Iterable<string>) => [...ids].reduce((s, id) => s + (books.get(`${id}.jpg`) ?? 0), 0);
  const keySet = (ids: Iterable<string>) => new Set([...ids].flatMap((id) => [...(keysOf.get(`${id}.jpg`) ?? [])]));
  const sampleKeys = keySet(sampleIds), restKeys = keySet(rest);
  const zy = join(ROOT, "proxy", "zhong-yang-661");
  return {
    annotatedImages: withBooks.length,
    step,
    sample: { images: sampleIds.size, annotatedBooks: booksOf(sampleIds), stageCaches: stages.length, stageCachesExactlyTheSample: stageMatchesSample, cardsReading: readers },
    smokeStride: { images: smokeIds.size, readByCards: "F-0 only, while the pipeline was built (src/eval/f0-cli.ts)" },
    cachedOutsideSample: { images: extra.length, inSmokeStride: extra.filter((id) => smokeIds.has(id)).length },
    untouched: { images: rest.length, annotatedBooks: booksOf(rest), distinctBooks: restKeys.size, distinctBooksAlsoInSample: [...restKeys].filter((k) => sampleKeys.has(k)).length, cardsReading: 0 },
    sampleDistinctBooks: sampleKeys.size,
    zhongYang: { filesAtDataRoot: existsSync(zy) ? readdirSync(zy).length : 0, cardsReading: 0 },
  };
}

/** What a sealed slice of n untouched Library Dataset images would give, at the yardstick's current per-image rates. */
function power(n: number, y: { photos: number; boxCount: number; labels: number; wrong: number; lo: number; hi: number }) {
  const per = (x: number) => (x / y.photos) * n;
  const halfWidth = ((y.hi - y.lo) / 2) * Math.sqrt(y.photos / n);
  return { images: n, boxCount: Math.round(per(y.boxCount)), labels: Math.round(per(y.labels)), wrongAccepts: Math.round(per(y.wrong)), wrongShareHalfWidth: r4(halfWidth), zeroNewWrongUpper: r4(ruleOfThree(Math.round(per(y.boxCount)))) };
}

function analyse(): void {
  const leak = splitLeakage();
  const use = reuse();
  const p = parts(use.byUse.gated + use.byUse.read);
  const ts1 = JSON.parse(readFileSync(join(REPO, "evals", "TS1", "metrics.json"), "utf8")).sets.yardstick;
  const y = { photos: ts1.photos, boxCount: ts1.boxCount, labels: ts1.labels.all.n, wrong: ts1.labels.all.k, lo: ts1.labels.all.share.lo, hi: ts1.labels.all.share.hi };
  const sizes = [...SLICES.filter((n) => n < p.untouched.images), p.untouched.images];
  const m = {
    card: "DL-5",
    date: new Date().toISOString().slice(0, 10),
    scope: "counts only; pilot-000 is real use (machine labels, INV-17); the yardstick is PROXY (library shelves), evaluation only (OC35)",
    prereg: "none: nothing is decided by a keep rule (see report.md)",
    roles: { trainable: TRAINABLE_ROLES, setsByRole: setsByRole(), registered: Object.keys(SET_REGISTRY).length },
    leakage: leak,
    yardstickReuse: use,
    yardstickParts: p,
    quarantine: { yardstickNow: y, slices: sizes.map((n) => power(n, y)) },
  };
  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, "metrics.json"), compactJson(m) + "\n");
  const rp = join(OUT, "report.md");
  const text = existsSync(rp) ? readFileSync(rp, "utf8") : "# DL-5 · eval hygiene\n\n";
  const head = text.includes(MARK) ? text.slice(0, text.indexOf(MARK)) : text.trimEnd() + "\n\n";
  writeFileSync(rp, head + MARK + "\n\n" + tables(m));
  log("evals/DL5/{metrics.json,report.md} written");
}

type M = {
  roles: { setsByRole: Record<string, number> };
  leakage: ReturnType<typeof splitLeakage>;
  yardstickReuse: ReturnType<typeof reuse>;
  yardstickParts: ReturnType<typeof parts>;
  quarantine: { slices: ReturnType<typeof power>[] };
};

const pct = (x: number | null) => (x === null ? "–" : `${(x * 100).toFixed(2)} %`);

function tables(m: M): string {
  const l = m.leakage, u = m.yardstickReuse, p = m.yardstickParts;
  const out: string[] = [];
  out.push("## Sets by role (`src/eval/set-roles.ts`)\n");
  out.push("| role | sets declared |\n|---|---:|");
  for (const [r, n] of Object.entries(m.roles.setsByRole)) out.push(`| \`${r}\` | ${n} |`);
  out.push(`\n## Work-level leakage across TS-0's frozen split (version \`${l.version}\`)\n`);
  out.push(`${l.labels} labels on ${l.photos.train} train and ${l.photos.val} val photos (${l.manifest.captureGroups} capture groups; ${l.manifest.withStore} photos carry a store id, ${l.manifest.withBookcase} a bookcase id).\n`);
  out.push("| works | count |\n|---|---:|");
  out.push(`| all | ${l.works.all} |\n| train only | ${l.works.trainOnly} |\n| val only | ${l.works.valOnly} |\n| held-out only | ${l.works.heldOutOnly} |\n| **in both train and val** | **${l.works.inBoth}** |`);
  out.push(`\nLabels on works in both: ${l.labelsOnWorksInBoth.train} train, ${l.labelsOnWorksInBoth.val} val. TS-2's training targets (strong class, train, two readers or more): ${l.ts2.trainWorks} works; **${l.ts2.valLabelsOnTrainWorks} of ${l.ts2.valLabels} val labels** (${l.ts2.valWorksInTrain} works) name one of them.\n`);
  out.push("| physical copies | count |\n|---|---:|");
  out.push(`| F-0g copy groups | ${l.copies.groups} |\n| groups spanning more than one photo | ${l.copies.groupsSpanningPhotos} |\n| groups straddling train and val | ${l.copies.groupsStraddlingSplit} |\n| copies in both splits, at most (= works in both) | ${l.copies.copiesInBothAtMost} |`);
  out.push(`\n## Yardstick reuse by card\n`);
  out.push(`${u.cards} eval folders with a \`metrics.json\`: **${u.byUse.gated} decided a keep condition on the yardstick**, ${u.byUse.read} read it without one, ${u.byUse["not read"]} did not read it. Gated by: ${Object.entries(u.gatedVia).map(([k, n]) => `${k} ${n}`).join(", ")}.\n`);
  out.push("| card | yardstick |\n|---|---|");
  for (const [c, v] of Object.entries(u.byCard)) out.push(`| ${c} | ${v} |`);
  out.push(`\n## The yardstick's parts\n`);
  out.push("| part | images | annotated books | cards that read it |\n|---|---:|---:|---|");
  out.push(`| F-0's sample (every ${p.step}th, middle of each stride) | ${p.sample.images} | ${p.sample.annotatedBooks} | ${p.sample.cardsReading} |`);
  out.push(`| smoke-test stride (stride starts) | ${p.smokeStride.images} | – | ${p.smokeStride.readByCards} |`);
  out.push(`| cached outside the sample (an early F-0 stage) | ${p.cachedOutsideSample.images} | – | F-0 (${p.cachedOutsideSample.inSmokeStride} of them in the smoke stride) |`);
  out.push(`| **untouched annotated images** | **${p.untouched.images}** | ${p.untouched.annotatedBooks} | ${p.untouched.cardsReading} |`);
  out.push(`| Zhong/Yang box set (boxes only) | ${p.zhongYang.filesAtDataRoot} files at the data root | – | ${p.zhongYang.cardsReading} |`);
  out.push(`\n${p.sample.stageCachesExactlyTheSample} of ${p.sample.stageCaches} yardstick stage caches hold exactly the sample's images; ${p.annotatedImages} annotated images with books are on disk. Books (ISBN, else title) in the sample: ${p.sampleDistinctBooks} distinct; in the untouched images: ${p.untouched.distinctBooks}, of which **${p.untouched.distinctBooksAlsoInSample} also stand in the sample** (one library's shelves).\n`);
  out.push("## A sealed slice of the untouched images, at the yardstick's current rates\n");
  out.push("| images | boxes | labels | wrong accepts | wrong-share interval, ± | 0 new wrong accepts: 95 % upper bound per box |\n|---:|---:|---:|---:|---:|---:|");
  for (const s of m.quarantine.slices) out.push(`| ${s.images} | ${s.boxCount} | ${s.labels} | ${s.wrongAccepts} | ${pct(s.wrongShareHalfWidth)} | ${pct(s.zeroNewWrongUpper)} |`);
  return out.join("\n") + "\n";
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const cmd = process.argv[2];
  if (cmd === "analyse") analyse();
  else {
    console.error("usage: node src/eval/dl5-cli.ts analyse");
    process.exit(2);
  }
}
